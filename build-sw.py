"""Writes sw.js with the list of app files and a version hash, so each deploy updates the offline cache."""
import hashlib, os

ROOT = os.path.dirname(os.path.abspath(__file__))
SKIP = {'sw.js', 'build-sw.py', 'README.md', '.nojekyll'}
files, h = [], hashlib.sha256()
for base, dirs, names in os.walk(ROOT):
    dirs[:] = sorted(d for d in dirs if not d.startswith('.') and d not in ('tests', 'node_modules'))
    for n in sorted(names):
        if n in SKIP or n.startswith('.'):
            continue
        p = os.path.join(base, n)
        rel = os.path.relpath(p, ROOT).replace(os.sep, '/')
        files.append('./' + rel)
        h.update(rel.encode()); h.update(open(p, 'rb').read())
version = h.hexdigest()[:10]
assets = ',\n  '.join("'%s'" % f for f in ['./'] + files)
sw = """// Generated by build-sw.py. Offline cache for English Gym.
const CACHE = 'english-gym-%s';
const ASSETS = [
  %s
];
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('message', e => { if (e.data === 'skipWaiting') self.skipWaiting(); });
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req).then(res => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
    return res;
  }).catch(() => req.mode === 'navigate' ? caches.match('./index.html') : Response.error())));
});
""" % (version, assets)
open(os.path.join(ROOT, 'sw.js'), 'w').write(sw)
print(version, len(files), 'files')
